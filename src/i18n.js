  function simplifyChineseText(value) {
    if (typeof value !== "string" || !value) return value;
    let output = value;
    zhHansPhraseMap.forEach(([source, replacement]) => {
      output = output.replaceAll(source, replacement);
    });
    return Array.from(output, (character) => zhHansCharMap[character] || character).join("");
  }

  function simplifyChineseValue(value) {
    if (typeof value === "string") return simplifyChineseText(value);
    if (Array.isArray(value)) return value.map(simplifyChineseValue);
    if (!value || typeof value !== "object") return value;
    return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, simplifyChineseValue(entry)]));
  }

  function interpolate(value, params) {
    return Object.entries(params || {}).reduce((text, [key, replacement]) => {
      return text.replaceAll(`{${key}}`, String(replacement));
    }, value);
  }

  function t(key, params) {
    const dictionary = dictionaries[currentLocale] || dictionaries[fallbackLocale] || {};
    const fallback = dictionaries[fallbackLocale] || {};
    return interpolate(dictionary[key] || fallback[key] || key, params);
  }

  function getLocalized(value) {
    if (!value || typeof value !== "object" || Array.isArray(value)) return value;
    return value[currentLocale] || value[fallbackLocale] || Object.values(value)[0] || "";
  }

  function setLocale(locale) {
    if (!supportedLocales.includes(locale)) return;
    if (locale === currentLocale) return;
    try {
      localStorage.setItem(localeKey, locale);
    } catch {
      // Locale storage is optional.
    }
    const nextPath = localizedPath(locale, `${window.location.pathname}${window.location.search}${window.location.hash}`);
    const currentPath = `${window.location.pathname}${window.location.search}${window.location.hash}`;
    window.WonderAnalytics?.track("locale_change", { locale, route: nextPath });
    const canUseLocaleRoute = /^https?:$/i.test(window.location.protocol);
    if (config.useLocaleRoutes !== false && canUseLocaleRoute && nextPath !== currentPath && typeof window.location.assign === "function") {
      window.location.assign(nextPath);
      return;
    }
    currentLocale = locale;
    document.documentElement.lang = locale;
    window.dispatchEvent(new CustomEvent("wonder:locale-change", { detail: { locale, legacyLocale: legacyLocale(locale) } }));
  }

  function locale() {
    return legacyLocale(currentLocale);
  }

  function legacyLocale(value = currentLocale) {
    return value === "zh-Hans" ? "zh-Hant" : value;
  }

  function actualLocale() {
    return currentLocale;
  }

  function localizeLegacyText(value) {
    return currentLocale === "zh-Hans" ? simplifyChineseText(value) : value;
  }

  const translatedTextNodes = new Map();
  const translatedAttributes = new Map();
  const translatedAttributeNames = ["aria-label", "title", "placeholder", "content", "alt"];

  function translateTextNode(node) {
    if (!node?.parentElement || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.parentElement.tagName)) return;
    // Locale names are self-identifying labels and must keep the approved
    // spelling in every language selector, including Simplified Chinese.
    if (node.parentElement.tagName === "OPTION" && node.parentElement.closest("select")) return;
    const previousSource = translatedTextNodes.get(node);
    if (previousSource !== undefined && node.data === simplifyChineseText(previousSource)) return;
    const source = node.data;
    const translated = simplifyChineseText(source);
    if (translated === source) return;
    translatedTextNodes.set(node, source);
    node.data = translated;
  }

  function translateElementAttributes(element) {
    if (!(element instanceof Element)) return;
    translatedAttributeNames.forEach((name) => {
      if (!element.hasAttribute(name)) return;
      const records = translatedAttributes.get(element) || new Map();
      const previousSource = records.get(name);
      const current = element.getAttribute(name) || "";
      if (previousSource !== undefined && current === simplifyChineseText(previousSource)) return;
      const translated = simplifyChineseText(current);
      if (translated === current) return;
      records.set(name, current);
      translatedAttributes.set(element, records);
      element.setAttribute(name, translated);
    });
  }

  function translateTree(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) translateTextNode(root);
    if (root.nodeType === Node.ELEMENT_NODE) translateElementAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      else translateElementAttributes(node);
    }
  }

  function restoreTranslatedDom() {
    translatedTextNodes.forEach((source, node) => {
      if (node.isConnected && node.data === simplifyChineseText(source)) node.data = source;
    });
    translatedTextNodes.clear();
    translatedAttributes.forEach((records, element) => {
      if (!element.isConnected) return;
      records.forEach((source, name) => {
        if (element.getAttribute(name) === simplifyChineseText(source)) element.setAttribute(name, source);
      });
    });
    translatedAttributes.clear();
  }

  function syncLocaleCompatibility() {
    if (document.documentElement.lang !== currentLocale) document.documentElement.lang = currentLocale;
    document.documentElement.dir = currentLocale === "ar" ? "rtl" : "ltr";
    document.documentElement.dataset.weightPlayLocale = currentLocale;
    document.querySelectorAll("select").forEach((select) => {
      const isLanguageSelect = select.querySelector('option[value="en"]') &&
        (select.id.toLowerCase().includes("locale") || select.id.toLowerCase().includes("language") || select.closest(".language-picker") || select.getAttribute("aria-label")?.toLowerCase() === "language");
      if (isLanguageSelect) {
        const options = new Map(Array.from(select.options, (option) => [option.value, option]));
        Array.from(select.options).forEach((option) => {
          if (!supportedLocales.includes(option.value)) option.remove();
        });
        supportedLocales.forEach((locale) => {
          const option = options.get(locale) || document.createElement("option");
          option.value = locale;
          option.textContent = localeLabels[locale] || locale;
          select.appendChild(option);
        });
      }
      if (select.querySelector(`option[value="${currentLocale}"]`)) select.value = currentLocale;
    });
    if (currentLocale === "zh-Hans") translateTree(document.documentElement);
    else restoreTranslatedDom();
  }

  function localizeInternalLinks(root = document) {
    if (!/^https?:$/i.test(window.location.protocol)) return;
    root.querySelectorAll?.("a[href]").forEach((anchor) => {
      const raw = anchor.getAttribute("href") || "";
      if (!raw || raw.startsWith("#") || /^(?:mailto:|tel:|javascript:)/i.test(raw)) return;
      let url;
      try { url = new URL(raw, document.baseURI); } catch { return; }
      if (url.origin !== window.location.origin) return;
      const path = url.pathname;
      const isLocalizedSurface = path === "/" || path === "/kids/" || /^\/(?:en|zh-tw|zh-cn|ja|ko|es|pt-br|fr|de|it|ru|hi|ar)\/(?:kids\/)?$/i.test(path) || /^\/(?:en|zh-tw|zh-cn|ja|ko|es|pt-br|fr|de|it|ru|hi|ar)\/games\/[a-z0-9-]+\/$/i.test(path) || /^\/games\/[a-z0-9-]+\/$/i.test(path);
      if (!isLocalizedSurface) return;
      anchor.href = new URL(localizedPath(currentLocale, `${path}${url.search}${url.hash}`), window.location.origin).href;
    });
  }

  function installCanvasLocaleBridge() {
    const prototype = window.CanvasRenderingContext2D?.prototype;
    if (!prototype || prototype.__weightPlayZhHansBridge) return;
    ["fillText", "strokeText", "measureText"].forEach((method) => {
      const original = prototype[method];
      if (typeof original !== "function") return;
      prototype[method] = function (value, ...args) {
        return original.call(this, localizeLegacyText(value), ...args);
      };
    });
    Object.defineProperty(prototype, "__weightPlayZhHansBridge", { value: true });
  }

  function syncStandardMainStartLabels() {
    document.querySelectorAll("[data-wp-main-start], #mainStartBtn, #startBtn, #startGameBtn, #showStageBtn, #wonderMainStart").forEach((node) => {
      if (node.closest?.('[data-runtime-localize="off"]')) return;
      const rect = node.getBoundingClientRect();
      const style = window.getComputedStyle(node);
      const active = style.display !== "none" && style.visibility !== "hidden" && rect.width > 0 && rect.height > 0;
      if (!active) return;
      const label = t("game.start");
      if (node.textContent.trim() !== label) node.textContent = label;
    });
  }

