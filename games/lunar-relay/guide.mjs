import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { copyByLocale, routes } from './locales.mjs?wp-media=9db423804d86ca7d';

const id = 'lunar-relay';
const host = 'https://weightplay.com';
const directory = '/games/lunar-relay/';
const poster = host + directory + 'art/poster.webp?wp-media=9db423804d86ca7d';
const blueprint = new URL('index.html', import.meta.url);
const catalog = vm.createContext({ window: {} });
for (const file of ['src/lobby-data.js?wp-media=9db423804d86ca7d','src/game-title-registry.js?wp-media=9db423804d86ca7d']) {
  const source = readFileSync(new URL('../../' + file, import.meta.url), 'utf8');
  vm.runInContext(source, catalog, {filename:file, timeout:2000});
}
const { WONDER_LOBBY: lobby, WEIGHTPLAY_GAME_TITLES: titles } = catalog.window;
const selected = lobby.games.find(game => game.id === id);
const live = selected?.status === 'playable' && !selected.internalOnly && !selected.internalTrial;
const inTopics = lobby.audiences.topicGameIds.includes(id);
const escape = value => value.replace(/[<>&"']/g, char => ({'<':'&lt;','>':'&gt;','&':'&amp;','"':'&quot;',"'":'&#39;'})[char]);
const block = (heading, content) => '<article class="game-info-section"><h3>' + escape(heading) + '</h3>' + content + '</article>';
const p = content => '<p>' + escape(content) + '</p>';
const publicUrl = slug => host + '/' + slug + directory;

export function renderEntry(locale) {
  const name = titles[id]?.[locale];
  const copy = copyByLocale[locale];
  const slug = routes[locale];
  if (!name || !copy || !slug || !selected) throw new Error('Incomplete game copy for ' + locale);
  const genre = selected.type[locale];
  const title = name + ' – ' + genre + ' | WeightPlay';
  const url = publicUrl(slug);
  const [goal, how, rules, finishing, related, question1, answer1, question2, answer2, newsTitle, facts, adaptation] = sections[locale];
  const faqs = [[question1, answer1], [question2, answer2]];
  const data = {'@context':'https://schema.org','@graph':[
    {'@type':'VideoGame',name,url,description:copy.summary,inLanguage:locale,image:poster,genre,
      gamePlatform:'Web browser',isAccessibleForFree:true,publisher:{'@type':'Organization',name:'WeightStudio',url:host}},
    {'@type':'FAQPage',inLanguage:locale,mainEntity:faqs.map(([name,text]) => ({'@type':'Question',name,acceptedAnswer:{'@type':'Answer',text}}))},
  ]};
  const metadata = [
    '<title data-runtime-localize="off">' + escape(title) + '</title>',
    '<meta name="robots" content="' + (live ? 'index,follow' : 'noindex,nofollow,noarchive') + '">',
    '<meta name="description" content="' + escape(copy.summary) + '">',
    '<link rel="canonical" href="' + url + '">',
    ...Object.entries({...routes,'x-default':'en'}).map(([key,value]) => '<link rel="alternate" hreflang="' + key + '" href="' + publicUrl(value) + '">'),
    ...Object.entries({type:'website',site_name:'WeightPlay',title,description:copy.summary,url,image:poster})
      .map(([key,value]) => '<meta property="og:' + key + '" content="' + escape(value) + '">'),
    ...Object.entries({card:'summary_large_image',title,description:copy.summary,image:poster})
      .map(([key,value]) => '<meta name="twitter:' + key + '" content="' + escape(value) + '">'),
    '<script type="application/ld+json">' + JSON.stringify(data).replaceAll('<','\\u003c') + '</script>',
  ].join('\n');

  const cards = ['moonlit-atrium','winglight-survey','lightday-dispatch'].flatMap(id => {
    const game = lobby.games.find(item => item.id === id && item.status === 'playable');
    const image = game?.art?.background;
    if (!image || !titles[id]?.[locale]) return [];
    return '<a class="game-info-related-card" data-game-id="' + id + '" data-wp-related-id="' + id + '" href="/' + slug + '/games/' + id +
      '/"><span class="game-info-related-poster"><img src="/' + escape(image.replace(/^\//,'')) + '" alt="" width="96" height="96" loading="lazy"></span><span>' +
      escape(titles[id][locale]) + '</span></a>';
  });
  const guide = [
    block(goal, '<p data-wp-intro-faq-source>' + escape(copy.summary) + '</p>'),
    block(how, p(copy.how)),
    block(rules, p(copy.cross) + p(copy.pair)),
    block(finishing, p(answer2)),
    ...(inTopics ? [block(newsTitle,p(facts) + p(adaptation))] : []),
    block('FAQ', '<dl>' + faqs.map(([q,a]) => '<dt>' + escape(q) + '</dt><dd>' + escape(a) + '</dd>').join('') + '</dl>'),
    ...(cards.length ? ['<section class="game-info-section game-info-related-section" data-wp-guide-related-interface="9"><h3>' +
      escape(related) + '</h3><div class="game-info-related-cards">' + cards.join('') + '</div></section>'] : []),
  ].join('\n');

  return readFileSync(blueprint,'utf8')
    .replace(/<html lang="[^"]+" dir="[^"]+"/, '<html lang="' + locale + '" dir="' + (locale === 'ar' ? 'rtl' : 'ltr') + '"')
    .replace(/<head(?: [^>]*)?>/, '<head data-wp-search-copy="2.0" data-wp-search-locale="' + locale +
      '" data-wp-search-title="' + escape(title) + '" data-wp-search-name="' + escape(name) + '">')
    .replace(/<!-- lunar-meta -->[\s\S]*?<!-- \/lunar-meta -->/, () => '<!-- lunar-meta -->\n' + metadata + '\n<!-- /lunar-meta -->')
    .replace(/<!-- lunar-guide -->[\s\S]*?<!-- \/lunar-guide -->/, () => '<!-- lunar-guide -->\n' + guide + '\n<!-- /lunar-guide -->')
    .replace(/ data-(?:wp-)?internal-only="[^"]*"/g, '')
    .replace('<body ', live ? '<body ' : '<body data-wp-internal-only="true" data-internal-only="1" ')
    .replace(/(id="mainReturn" href=")[^"]*/, (_,prefix) => prefix + '/' + slug + '/' + (live ? '' : '?preview=1'))
    .replace(/(<h1 id="gameTitle"[^>]*>)[^<]*/, (_,prefix) => prefix + escape(name))
    .replace(/(data-word="([A-Za-z0-9]+)"[^>]*>)[^<]*(?=<)/g, (_,prefix,key) => prefix + escape(copy[key]))
    .replace(/(aria-label=")Signals"/, (_,prefix) => prefix + escape(copy.signals) + '"')
    .replace(/(aria-label=")Telescopes"/, (_,prefix) => prefix + escape(copy.stations) + '"');
}
