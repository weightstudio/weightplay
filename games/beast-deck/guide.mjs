const SEGMENTS = Object.freeze({ "zh-Hant":"zh-tw", "zh-Hans":"zh-cn", "pt-BR":"pt-br" });
const escape = s => String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');

export function replaceBeastGuide(html, locale = 'en') {
  const c = guideCopy[locale];
  const progression = progressionCopy[locale];
  const faq = faqCopy[locale];
  const tags = gameplayTags[locale];
  const related = relatedCopy[locale];
  const comparison = marketComparison[locale];
  if (!c || !progression || !faq || !tags || !related || !comparison) throw Error(`Missing Beast guide locale: ${locale}`);

  const summary = /<span\b[^>]*data-ui="menuHint"[^>]*>[\s\S]*?<\/span>/;
  if (!summary.test(html)) throw Error('Beast Main summary slot missing');
  html = html.replace(summary, () => `<span class="main-summary" data-ui="menuHint" data-beast-authored-summary="true" data-runtime-localize="off">${escape(c[0])}</span>`);

  const pattern = /<section\b[^>]*class="game-page-info game-page-info-static"[^>]*>[\s\S]*?<\/section>/;
  const old = html.match(pattern)?.[0];
  if (!old) throw Error('Beast guide slot missing');
  const title = old.match(/<h2\b[^>]*>([\s\S]*?)<\/h2>/)?.[1];
  if (!title) throw Error('Beast official guide title missing');

  const faqHtml = faq.map(([question, answer]) => `<div><dt>${escape(question)}</dt><dd>${escape(answer)}</dd></div>`).join('');
  const tagHtml = tags.map(tag => `<span>${escape(tag)}</span>`).join('');
  const segment = SEGMENTS[locale] || locale;
  const relatedHtml = related.games.map(([name, description], index) => {
    const game = RELATED[index];
    return `<a class="game-info-related-card" href="/${segment}/games/${game.id}/"><img src="${game.image}" alt="" width="320" height="320" loading="lazy" decoding="async" /><span class="game-info-related-copy"><strong>${escape(name)}</strong><span>${escape(description)}</span></span></a>`;
  }).join('');

  return html.replace(pattern, () => `<section id="gameGuide" class="game-page-info game-page-info-static" data-wp-guide-complete="true" data-runtime-localize="off"><div class="game-info-hero"><div class="game-info-title"><h2>${title}</h2><p>${escape(c[0])}</p></div></div><div class="game-info-sections"><div class="game-info-section"><h3>${escape(c[1])}</h3><ol>${c.slice(2,5).map(s=>`<li>${escape(s)}</li>`).join('')}</ol></div><div class="game-info-section"><h3>${escape(c[5])}</h3><p>${escape(c[6])}</p></div><div class="game-info-section"><h3>${escape(progression[0])}</h3><p>${escape(progression[1])}</p></div><div class="game-info-section"><h3>${escape(c[7])}</h3><p>${escape(c[8])}</p></div><div class="game-info-section"><h3>FAQ</h3><dl>${faqHtml}</dl></div><div class="game-info-section game-info-related-section"><h3>${escape(related.heading)}</h3><div class="game-info-related">${relatedHtml}</div></div></div><article class="game-info-section game-info-comparison" data-wp-market-comparison="1.3.0" data-comparison-locale="${escape(locale)}" data-runtime-localize="off"><h3>${escape(comparison.heading)}</h3><p><strong data-wp-gameplay-tags-label>${escape(comparison.tagsLabel)}</strong></p><div class="game-info-tags" data-wp-gameplay-tags="1.3.0">${tagHtml}</div><p><strong><bdi>Slay the Spire</bdi>:</strong> <span data-wp-comparison-shared>${escape(comparison.body)}</span></p><p>${escape(comparison.disclaimer)}</p><p><a href="${MARKET_SOURCE}" rel="nofollow noopener noreferrer">${escape(comparison.sourceLabel)}</a></p></article></section>`);
}
