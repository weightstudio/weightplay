export function word(locale, key, values = {}) {
  const language = Object.hasOwn(ROUTES, locale) ? locale : 'en';
  const text = language === 'en' || language === 'zh-Hant'
    ? base[key]?.[language === 'en' ? 0 : 1]
    : extras[language]?.[key];
  if (text === undefined) throw new Error('Unknown pinball string ' + key);
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values,name) ? String(values[name]) : match);
}
